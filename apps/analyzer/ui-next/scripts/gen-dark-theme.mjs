// Generates src/app/theme-dark.css from Tailwind's own palette (node_modules/tailwindcss/theme.css),
// so the dark theme uses the exact Tailwind values instead of hand-copied ones.
//
// How the dark theme works: the app's components use light-theme utilities (bg-white,
// text-slate-900, border-slate-200 ...). Those utilities read CSS variables
// (--color-slate-900 ...). In dark mode we re-point the variables, e.g. slate-900 becomes the
// colour of slate-50, so the same classes render dark with no per-component `dark:` variants.
// `.palette-default` restores the original palette for a subtree (the hero is dark in both themes).
//
// Run:  node scripts/gen-dark-theme.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const theme = readFileSync(path.join(root, "node_modules", "tailwindcss", "theme.css"), "utf8");

const palette = {};
for (const match of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  (palette[match[1]] ??= {})[match[2]] = match[3].trim();
}
const white = /--color-white:\s*([^;]+);/.exec(theme)?.[1]?.trim() ?? "#fff";

// target shade in the dark theme for each light shade (950 is left alone: it is used for
// dark text on bright buttons, which must stay dark)
const NEUTRAL = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 500, 500: 400, 600: 300, 700: 200, 800: 100, 900: 50 };
const CHROMA = { 50: 950, 100: 900, 200: 800, 300: 700, 600: 400, 700: 300, 800: 200, 900: 100 };
const families = { slate: NEUTRAL, sky: CHROMA, emerald: CHROMA, red: CHROMA, amber: CHROMA, rose: CHROMA };

const dark = [];
const original = [];
for (const [family, map] of Object.entries(families)) {
  for (const [from, to] of Object.entries(map)) {
    const target = palette[family]?.[to];
    const source = palette[family]?.[from];
    if (!target || !source) throw new Error(`missing ${family}-${from}/${to} in theme.css`);
    dark.push(`  --color-${family}-${from}: ${target};`);
    original.push(`  --color-${family}-${from}: ${source};`);
  }
}
dark.push(`  --color-white: ${palette.slate[900]};`);
original.push(`  --color-white: ${white};`);

const css = `/* GENERATED by scripts/gen-dark-theme.mjs - do not edit by hand. */

html[data-theme="dark"] {
  color-scheme: dark;
  --background: ${palette.slate[950]};
  --foreground: ${palette.slate[50]};
  --surface: ${palette.slate[900]};
  --border: ${palette.slate[700]};
${dark.join("\n")}
}

/* A subtree that keeps the original (light-theme) palette, e.g. the always-dark hero. */
.palette-default {
${original.join("\n")}
}

/* --- Hand-written colours that do not come from Tailwind utilities ---------- */
html[data-theme="dark"] .badge-queued { color: #fcd34d; }
html[data-theme="dark"] .badge-running { color: #93c5fd; }
html[data-theme="dark"] .badge-done { color: #86efac; }
html[data-theme="dark"] .badge-failed { color: #fca5a5; }
html[data-theme="dark"] .badge-neutral { color: #cbd5e1; }

html[data-theme="dark"] .markdown-body { color: #cbd5e1; }
html[data-theme="dark"] .markdown-body h1,
html[data-theme="dark"] .markdown-body h2,
html[data-theme="dark"] .markdown-body h3,
html[data-theme="dark"] .markdown-body h4,
html[data-theme="dark"] .markdown-body th { color: #f1f5f9; }
html[data-theme="dark"] .markdown-body strong { color: #f8fafc; }
html[data-theme="dark"] .markdown-body a { color: #7dd3fc; }
html[data-theme="dark"] .markdown-body blockquote { border-left-color: #64748b; color: #cbd5e1; }
`;

writeFileSync(path.join(root, "src", "app", "theme-dark.css"), css);
console.log(`wrote src/app/theme-dark.css (${css.length} bytes)`);
