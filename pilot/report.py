"""Turn pilot/results.json into docs/pilot.md. Every number in the report is computed here from the JSON."""
from __future__ import annotations

import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


#: Analysis written after reading the run; the numbers themselves come from the JSON.
EXPLAIN = {
    ("cmd-popen", "fix"): (
        "The patch is the right fix and its command-injection probe went from reproduced to not reproduced. "
        "The status is `FIX_PARTIAL` because the rules also raised a `path-traversal` finding (CWE-22, medium) on "
        "`os.popen(...).read()`, which is a misclassification by the rules, and the patch check demands an exploit "
        "test for every attack class whose finding disappeared. So a false positive of the rules turned into a "
        "missing-test gap. The check did what it is built to do; the cost of the rules' wrong guess is paid in a "
        "`PARTIAL` that says exactly what is missing."),
}


def med(values):
    values = [v for v in values if v is not None]
    return round(statistics.median(values), 1) if values else None


def p90(values):
    values = sorted(v for v in values if v is not None)
    return round(values[min(len(values) - 1, int(len(values) * 0.9))], 1) if values else None


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def build(r: dict) -> str:
    L = []
    meta = r["meta"]
    L.append("# Closed pilot (31 Oct 2026)")
    L.append("")
    L.append("Generated by `pilot/report.py` from `pilot/results.json`; reproduce with `python pilot/run_pilot.py` "
             f"(results digest `{r['digest'][:16]}`). Nothing in this document was typed in by hand except the "
             "explanations around the numbers.")
    L.append("")
    L.append("## What was run")
    L.append("")
    L.append(f"- No model was called (`model_called: {str(meta['model_called']).lower()}`). No data left this machine.")
    L.append("- The rules ran in-process on the labelled samples and on the synthetic corpus. Samples that are not ours "
             "were only read, never executed.")
    L.append(f"- Everything that executes code ran in worker containers (`{meta.get('image')}`, "
             "`--network none --read-only`), and the code it executed is the synthetic corpus of `pilot/cases.py`.")
    L.append(f"- {meta.get('docker', 'docker: n/a')}; Python {meta['python']}; one machine; `{meta['date']}`.")
    L.append("")

    if r.get("samples"):
        L.append("## A. The rules on the five samples (read, never run)")
        L.append("")
        rows = []
        th = tl = 0
        for s in r["samples"]:
            if s["labelled"]:
                th += s["hits"]
                tl += s["labels"]
            rows.append([s["sample"], s["findings"], s["labels"] if s["labelled"] else "n/a (not in the repo)",
                         f"{s['hits']}/{s['labels']}" if s["labelled"] else "n/a",
                         ", ".join(s["missed"]) or ("none" if s["labelled"] else "n/a"),
                         s["unmatched_findings"] if s["labelled"] else "n/a", s["ms"]])
        L.append(table(["sample", "findings", "labels", "label hits (+-2 lines)", "missed", "findings away from any label", "ms"], rows))
        L.append("")
        L.append(f"Over the four labelled samples: {th} of {tl} labels have a finding within 2 lines. A hit is a "
                 "proximity match, not a verified detection; a finding can overlap several labels. These are not "
                 "precision and recall. Labels of `user_service.py` were written by the assistant, not by the file's "
                 "author; the fifth sample (`auth_service.py`) has no labels in this repository.")
        L.append("")

    cr = r["corpus_rules"]
    L.append("## B. The rules on the synthetic corpus")
    L.append("")
    classes = sorted({c["class"] for c in cr})
    rows = []
    for k in classes + ["all"]:
        part = [c for c in cr if k == "all" or c["class"] == k]
        n = {o: sum(1 for c in part if c["outcome"] == o) for o in ("TP", "FN", "FP", "TN")}
        rows.append([k, len(part), n["TP"], n["FN"], n["FP"], n["TN"]])
    L.append(table(["class", "cases", "vulnerable found (TP)", "vulnerable missed (FN)",
                    "safe twin flagged (FP)", "safe twin quiet (TN)"], rows))
    L.append("")
    L.append(table(["case", "vulnerable", "outcome", "flagged by"],
                   [[c["case"], "yes" if c["vulnerable"] else "no", c["outcome"], ", ".join(c["flagged_by"]) or "-"] for c in cr]))
    L.append("")

    if "probes" in r:
        pr = r["probes"]
        agree = sum(1 for p in pr if p["agrees"])
        err = [p for p in pr if p["agrees"] is None]
        L.append("## C. The exploit probes against the truth")
        L.append("")
        L.append(f"{agree} of {len(pr)} probe results agree with the truth by construction "
                 f"(reproduced on vulnerable code, not reproduced on its safe twin); {len(err)} sandbox errors. "
                 f"Time per probe run (a container each): median {med([p['ms'] for p in pr])} ms, "
                 f"p90 {p90([p['ms'] for p in pr])} ms.")
        bad = [p for p in pr if p["agrees"] is False]
        if bad:
            L.append("")
            L.append("Disagreements: " + ", ".join(f"{p['case']} ({p['result']})" for p in bad))
        L.append("")

    if "scenarios" in r:
        sc = r["scenarios"]
        L.append("## D. The patch check on scripted patches")
        L.append("")
        statuses = ["FIX_VERIFIED", "FIX_PARTIAL", "FIX_REJECTED", "FIX_UNVERIFIED"]
        rows = [[s, sum(1 for x in sc if x["expected"] == s), sum(1 for x in sc if x["actual"] == s)] for s in statuses]
        rows.append(["other (crash)", 0, sum(1 for x in sc if x["actual"] not in statuses)])
        nocase = sorted({c["case"] for c in cr} - {x["case"] for x in sc})
        L.append(f"{len(sc)} scripted patches on {len({x['case'] for x in sc})} vulnerable cases. Expected statuses were "
                 "written in `run_pilot.py` before the run.")
        L.append("")
        L.append(table(["status", "expected", "actual"], rows))
        L.append("")
        L.append(f"Cases with no patch at all (status `NO_PATCH`, nothing proposed): {len(nocase)}: " + ", ".join(nocase) + ".")
        L.append("")
        match = [x for x in sc if x["match"]]
        surprises = [x for x in sc if not x["match"]]
        limits = [x for x in sc if x["note"].startswith("KNOWN LIMIT") and x["match"]]
        L.append(f"{len(match)} of {len(sc)} scenarios got the expected status; {len(limits)} of those confirm "
                 "a documented limit of the checks rather than a success (see below). "
                 f"Surprises (status differs from what was written down): {len(surprises)}.")
        L.append("")
        if surprises:
            L.append(table(["case", "patch", "expected", "actual", "reason"],
                           [[x["case"], x["kind"], x["expected"], x["actual"], (x["reason"] or "").replace("|", "/")[:160]] for x in surprises]))
            L.append("")
        for x in surprises:
            why = EXPLAIN.get((x["case"], x["kind"]))
            if why:
                L.append(f"- **Explained surprise:** `{x['case']}` / `{x['kind']}`. {why}")
        for x in limits:
            L.append(f"- **Limit confirmed:** `{x['case']}` / `{x['kind']}` got `{x['actual']}`. {x['note']}")
        L.append("")
        L.append("Per kind of patch:")
        L.append("")
        kinds = sorted({x["kind"] for x in sc})
        L.append(table(["patch", "n", "statuses reached"],
                       [[k, sum(1 for x in sc if x["kind"] == k),
                         ", ".join(f"{s.replace('FIX_', '')} x{sum(1 for x in sc if x['kind'] == k and x['actual'] == s)}"
                                   for s in statuses + ['CRASH'] if any(x['kind'] == k and x['actual'] == s for x in sc))]
                        for k in kinds]))
        L.append("")
        L.append(f"Time per patch check (validator, rules and probes in containers): median {med([x['ms'] for x in sc])} ms, "
                 f"p90 {p90([x['ms'] for x in sc])} ms, max {max(x['ms'] for x in sc)} ms.")
        L.append("")

    if "sandbox_failures" in r:
        f = r["sandbox_failures"]
        L.append("## Sandbox")
        L.append("")
        cc = [x for x in r.get("scenarios", []) if x.get("isolation")]
        ok = sum(1 for x in cc if x["cleanup_confirmed"] is True)
        L.append(f"Sandbox failures (errors, unverified results, unconfirmed cleanup): {len(f)}. "
                 f"Container cleanup confirmed on {ok} of {len(cc)} patch checks that ran in a container.")
        for x in f:
            L.append(f"- {x.get('phase')} / {x.get('case')} / {x.get('kind', '')}: {x.get('error') or x.get('reason') or x.get('status')}")
        L.append("")

    if "determinism" in r:
        d = r["determinism"]
        L.append("## Determinism")
        L.append("")
        L.append(f"The fix scenarios for {', '.join(d['scenarios'])} were run twice: the deterministic part of the "
                 f"results is {'byte-identical' if d['identical'] else 'NOT identical'}.")
        L.append("")

    L.append("## What this does not show")
    L.append("")
    L.append("- The corpus is small, written by us, and its truth is true by construction. Agreement with it is a "
             "check that the tools do what they were built to do, not an accuracy figure on real code.")
    L.append("- Python only. The probes need the caller to name the function to attack.")
    L.append("- No model produced any of these patches. How good model patches are, and how often the checking loop "
             "converges, was not measured (that would send code to a provider and needs the go/no-go for "
             "external processing first).")
    L.append("- One machine, one run; the times are indicative.")
    L.append("- This document makes no claim that the hub fixes vulnerabilities automatically.")
    L.append("")
    return "\n".join(L)


def main() -> int:
    src = os.path.join(HERE, "results.json")
    dst = os.path.join(ROOT, "docs", "pilot.md")
    with open(src, encoding="utf-8") as fh:
        r = json.load(fh)
    with open(dst, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(build(r))
    print("wrote", dst)
    return 0


if __name__ == "__main__":
    sys.exit(main())